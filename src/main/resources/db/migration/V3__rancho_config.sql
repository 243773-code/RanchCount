CREATE TABLE IF NOT EXISTS rancho_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rancho VARCHAR(100) NOT NULL,
    proposito VARCHAR(120) NOT NULL,
    hectareas_totales NUMERIC(10, 2),
    ubicacion_texto VARCHAR(160),
    creado_at TIMESTAMP NOT NULL,
    actualizado_at TIMESTAMP NOT NULL
);
